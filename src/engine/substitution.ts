// Dynamic S-box generator and substitution helpers

import { expandDeterministicPRNG } from './argon2';

export async function generateDynamicSBox(seedKey: Uint8Array): Promise<{ SBOX: Uint8Array, INV_SBOX: Uint8Array }> {
    // Expand deterministic bytes to generate our random affine transforms
    // We use a fixed info string to ensure cross-version compatibility
    const prngBytes = await expandDeterministicPRNG(seedKey, 1024, "zDays-v5-SBox-Entropy-v4");
    
    let prngIdx = 0;

    function createInvertibleMatrix(): Uint8Array {
        const M = new Uint8Array(8);
        for (let i = 0; i < 8; i++) M[i] = 1 << i; // Start with Identity matrix
        
        // Perform 256 random row operations to fully mix the matrix
        // Row swaps and additions preserve the matrix's invertibility
        for (let k = 0; k < 256; k++) {
            const op = prngBytes[prngIdx++];
            const r1 = op & 7;
            const r2 = (op >>> 3) & 7;
            if (r1 !== r2) {
                if ((op & 128) === 0) {
                    // Swap rows
                    const t = M[r1];
                    M[r1] = M[r2];
                    M[r2] = t;
                } else {
                    // Add row r2 to r1 (XOR in GF(2))
                    M[r1] ^= M[r2];
                }
            }
        }
        return M;
    }

    const M1 = createInvertibleMatrix();
    const M2 = createInvertibleMatrix();
    
    const c1 = prngBytes[prngIdx++];
    const c2 = prngBytes[prngIdx++];

    // Matrix-vector multiplication over GF(2)
    function matMul(mat: Uint8Array, val: number): number {
        let out = 0;
        for (let i = 0; i < 8; i++) {
            let dot = mat[i] & val;
            dot ^= dot >>> 4;
            dot ^= dot >>> 2;
            dot ^= dot >>> 1;
            if (dot & 1) out |= (1 << i);
        }
        return out;
    }

    // Construct the S-Box using S(x) = M_2 * Core(M_1 * x ^ c_1) ^ c_2
    const SBOX = new Uint8Array(256);
    const INV_SBOX = new Uint8Array(256);

    // The SM4 S-box. It has optimal properties (DU=4, NL=112) like AES, 
    // but avoids using the AES S-box itself. Used as the fixed core permutation.
    const CORE_SBOX = new Uint8Array([
        0xd6, 0x90, 0xe9, 0xfe, 0xcc, 0xe1, 0x3d, 0xb7, 0x16, 0xb6, 0x14, 0xc2, 0x28, 0xfb, 0x2c, 0x05,
        0x2b, 0x67, 0x9a, 0x76, 0x2a, 0xbe, 0x04, 0xc3, 0xaa, 0x44, 0x13, 0x26, 0x49, 0x86, 0x06, 0x99,
        0x9c, 0x42, 0x50, 0xf4, 0x91, 0xef, 0x98, 0x7a, 0x33, 0x54, 0x0b, 0x43, 0xed, 0xcf, 0xac, 0x62,
        0xe4, 0xb3, 0x1c, 0xa9, 0xc9, 0x08, 0xe8, 0x95, 0x80, 0xdf, 0x94, 0xfa, 0x75, 0x8f, 0x3f, 0xa6,
        0x47, 0x07, 0xa7, 0xfc, 0xf3, 0x73, 0x17, 0xba, 0x83, 0x59, 0x3c, 0x19, 0xe6, 0x85, 0x4f, 0xa8,
        0x68, 0x6b, 0x81, 0xb2, 0x71, 0x64, 0xda, 0x8b, 0xf8, 0xeb, 0x0f, 0x4b, 0x70, 0x56, 0x9d, 0x35,
        0x1e, 0x24, 0x0e, 0x5e, 0x63, 0x58, 0xd1, 0xa2, 0x25, 0x22, 0x7c, 0x3b, 0x01, 0x21, 0x78, 0x87,
        0xd4, 0x00, 0x46, 0x57, 0x9f, 0xd3, 0x27, 0x52, 0x4c, 0x36, 0x02, 0xe7, 0xa0, 0xc4, 0xc8, 0x9e,
        0xea, 0xbf, 0x8a, 0xd2, 0x40, 0xc7, 0x38, 0xb5, 0xa3, 0xf7, 0xf2, 0xce, 0xf9, 0x61, 0x15, 0xa1,
        0xe0, 0xae, 0x5d, 0xa4, 0x9b, 0x34, 0x1a, 0x55, 0xad, 0x93, 0x32, 0x30, 0xf5, 0x8c, 0xb1, 0xe3,
        0x1d, 0xf6, 0xe2, 0x2e, 0x82, 0x66, 0xca, 0x60, 0xc0, 0x29, 0x23, 0xab, 0x0d, 0x53, 0x4e, 0x6f,
        0xd5, 0xdb, 0x37, 0x45, 0xde, 0xfd, 0x8e, 0x2f, 0x03, 0xff, 0x6a, 0x72, 0x6d, 0x6c, 0x5b, 0x51,
        0x8d, 0x1b, 0xaf, 0x92, 0xbb, 0xdd, 0xbc, 0x7f, 0x11, 0xd9, 0x5c, 0x41, 0x1f, 0x10, 0x5a, 0xd8,
        0x0a, 0xc1, 0x31, 0x88, 0xa5, 0xcd, 0x7b, 0xbd, 0x2d, 0x74, 0xd0, 0x12, 0xb8, 0xe5, 0xb4, 0xb0,
        0x89, 0x69, 0x97, 0x4a, 0x0c, 0x96, 0x77, 0x7e, 0x65, 0xb9, 0xf1, 0x09, 0xc5, 0x6e, 0xc6, 0x84,
        0x18, 0xf0, 0x7d, 0xec, 0x3a, 0xdc, 0x4d, 0x20, 0x79, 0xee, 0x5f, 0x3e, 0xd7, 0xcb, 0x39, 0x48
    ]);

    for (let x = 0; x < 256; x++) {
        const step1 = matMul(M1, x) ^ c1;
        const coreVal = CORE_SBOX[step1];
        const step2 = matMul(M2, coreVal) ^ c2;
        
        SBOX[x] = step2;
        INV_SBOX[step2] = x;
    }

    return { SBOX, INV_SBOX };
}

export function substitute(block: Uint8Array, sbox: Uint8Array): void {
    for (let i = 0; i < block.length; i++) block[i] = sbox[block[i]];
}
export function inverseSubstitute(block: Uint8Array, invSbox: Uint8Array): void {
    for (let i = 0; i < block.length; i++) block[i] = invSbox[block[i]];
}
